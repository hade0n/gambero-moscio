export const INGREDIENT_MAP = Object.freeze(
  Object.fromEntries(INGREDIENTS.map((item) => [item.id, Object.freeze(item)])),
);

export const GRILLABLE_INGREDIENTS = Object.freeze(
  INGREDIENTS.filter((item) => item.requiresGrill),
);

export function getIngredient(id) {
  return INGREDIENT_MAP[id] || null;
}

export function isValidIngredientId(id) {
  return Boolean(INGREDIENT_MAP[id]);
}
